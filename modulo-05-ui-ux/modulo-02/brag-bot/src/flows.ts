import { googleAI } from '@genkit-ai/google-genai';
import { genkit, z } from 'genkit';
import { existsSync } from 'node:fs';
import { v4 as uuidv4 } from 'uuid';

// Variables already set in the environment take precedence over the .env file.
if (existsSync('.env')) {
  process.loadEnvFile();
}

const ai = genkit({
  plugins: [googleAI({ apiKey: process.env['GOOGLE_API_KEY'] })],
  model: googleAI.model('gemini-2.5-flash', { temperature: 0.8 }),
});

export const BragInputSchema = z.object({
  definition: z.string().describe("The user's informal draft about their work achievement"),
});

export const BragSchema = z.object({
  title: z.string().describe('Main action plus high-level result'),
  context: z.string().describe('Original situation or problem: what was broken, slow or missing'),
  actionTaken: z
    .string()
    .describe('Step-by-step technical or strategic action taken to solve the problem'),
  businessImpact: z
    .string()
    .describe('Business impact, such as time saved or reduction in failures'),
  metrics: z
    .array(z.string())
    .describe('Strictly quantifiable data only, for example "50% reduction"'),
  technologiesUsed: z
    .array(z.string())
    .describe('Tools, languages and platforms mentioned or inferred from the draft'),
});

// The model fills in BragSchema; the id is generated by the flow, never by the LLM.
export const BragOutputSchema = BragSchema.extend({
  id: z.string().uuid().describe('Unique identifier generated for this brag'),
});

export const bragGeneratorFlow = ai.defineFlow(
  {
    name: 'bragGeneratorFlow',
    inputSchema: BragInputSchema,
    outputSchema: BragOutputSchema,
  },
  async (input) => {
    const prompt = `You are a Senior Career Consultant focused on Individual Development Plans (IDP) for Software Engineers.

Your goal is to turn the user's informal draft into an executive Brag Document.

Rules:
1. Use a professional, objective, impact-focused tone, with no emotional adjectives.
2. If exact metrics do not exist, infer the nature of the metric based on the action taken.
3. Follow the JSON schema STRICTLY.
4. The output must respect the original language of the input (if the draft is in Portuguese, answer in Portuguese).

User draft:
${input.definition}`;

    const { output } = await ai.generate({
      prompt,
      output: { schema: BragSchema },
    });

    if (!output) {
      throw new Error('The model did not return a valid brag document.');
    }

    return { ...output, id: uuidv4() };
  },
);
